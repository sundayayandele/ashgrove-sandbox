"""Generate the Kustomize manifests for Kubernetes and OpenShift.

    python deploy/k8s/generate.py          # write files
    python deploy/k8s/generate.py --check  # fail if committed files are stale (CI)

Layout:
  base/                       six services, config, Keycloak, Mailpit
  components/observability/   OTel collector, Tempo, Prometheus, Grafana (optional)
  overlays/kubernetes/        namespace + Ingress (any ingress controller, nginx by default)
  overlays/openshift/         namespace + Routes; pods run under the restricted-v2 SCC
"""

from __future__ import annotations

