def overlays() -> dict[str, list[dict]]:
    public = ["crm", "orders", "helpdesk", "lending", "hr", "docs", "keycloak", "mailpit"]
    ns = lambda: {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": "ashgrove", "labels": LABELS}}  # noqa: E731
    ingress = {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "Ingress",
        "metadata": {"name": "ashgrove", "labels": LABELS},
        "spec": {
            "ingressClassName": "nginx",
            "rules": [
                {
                    "host": f"{n}.ashgrove.localtest.me",
                    "http": {
                        "paths": [
                            {"path": "/", "pathType": "Prefix", "backend": {"service": {"name": n, "port": {"name": "http"}}}}
                        ]
                    },
                }
                for n in public
            ],
        },
    }
    k8s = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "namespace": "ashgrove",
        "resources": ["namespace.yaml", "../../base", "ingress.yaml"],
        "components": ["../../components/observability"],
        "patches": [{"path": "mailpit-nonroot.yaml"}],
    }
    # Vanilla Kubernetes does not assign a UID like OpenShift does; give Mailpit one explicitly.
    mailpit_patch = {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": "mailpit"},
        "spec": {"template": {"spec": {"securityContext": {"runAsUser": 1000, "runAsGroup": 1000}}}},
    }
    routes = [
        {
            "apiVersion": "route.openshift.io/v1",
            "kind": "Route",
            "metadata": {"name": n, "labels": LABELS},
            "spec": {
                "to": {"kind": "Service", "name": n},
                "port": {"targetPort": "http"},
                "tls": {"termination": "edge", "insecureEdgeTerminationPolicy": "Redirect"},
            },
        }
        for n in public
    ]
    # On OpenShift the Keycloak public URL is the Route host. Set CLUSTER_APPS_DOMAIN before applying.
    config_patch = {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {"name": "ashgrove-config"},
        "data": {
            "KEYCLOAK_PUBLIC_URL": "https://keycloak-ashgrove.apps.CLUSTER_APPS_DOMAIN",
            "KEYCLOAK_ISSUER": "https://keycloak-ashgrove.apps.CLUSTER_APPS_DOMAIN/realms/ashgrove",
        },
    }
    ocp = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "namespace": "ashgrove",
        "resources": ["namespace.yaml", "../../base", "routes.yaml"],
        "components": ["../../components/observability"],
        "patches": [{"path": "config-patch.yaml"}],
    }
    return {
        "overlays/kubernetes/namespace.yaml": [ns()],
        "overlays/kubernetes/ingress.yaml": [ingress],
        "overlays/kubernetes/kustomization.yaml": [k8s],
        "overlays/kubernetes/mailpit-nonroot.yaml": [mailpit_patch],
        "overlays/openshift/namespace.yaml": [ns()],
        "overlays/openshift/routes.yaml": routes,
        "overlays/openshift/config-patch.yaml": [config_patch],
        "overlays/openshift/kustomization.yaml": [ocp],
    }


def render() -> dict[Path, str]:
    files = {**base(), **observability(), **overlays()}
    out = {ROOT / k: HEADER + yaml.safe_dump_all(v, sort_keys=False) for k, v in files.items()}
    # Copies of config files Kustomize needs inside its tree.
    out[ROOT / "base/realm/ashgrove-realm.json"] = (
        json.dumps(json.loads((REPO / "deploy/keycloak/ashgrove-realm.json").read_text()), indent=2) + "\n"
    )
    for f in ("otel-collector.yaml", "tempo.yaml", "prometheus.yml"):
        out[ROOT / f"components/observability/files/{f}"] = (REPO / "deploy/observability" / f).read_text()
    out[ROOT / "components/observability/files/datasources.yaml"] = (
        REPO / "deploy/observability/grafana/datasources.yaml"
    ).read_text()
    return out


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    files = render()
    if ap.parse_args().check:
        stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
        for p in stale:
            print(f"out of date: {p.relative_to(REPO)}")
        sys.exit(1 if stale else 0)
    for p, t in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t)
    print(f"wrote {len(files)} files")
