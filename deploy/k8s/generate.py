ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[1]
sys.path.insert(0, str(REPO / "src"))
from ashgrove import SERVICES, __version__  # noqa: E402

IMAGE = f"ghcr.io/sundayayandele/ashgrove-sandbox:{__version__}"
LABELS = {"app.kubernetes.io/part-of": "ashgrove-sandbox"}
SECURE_POD = {"runAsNonRoot": True, "seccompProfile": {"type": "RuntimeDefault"}}
SECURE_CONTAINER = {"allowPrivilegeEscalation": False, "capabilities": {"drop": ["ALL"]}}
HEADER = "# Generated by deploy/k8s/generate.py. Edit the script, not this file.\n"


def labels(name: str) -> dict:
    return {**LABELS, "app.kubernetes.io/name": name}


def service(name: str, port: int, target: int | None = None, extra_ports: list[dict] | None = None) -> dict:
    ports = [{"name": "http", "port": port, "targetPort": target or port}] + (extra_ports or [])
    return {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": name, "labels": labels(name)},
        "spec": {"selector": {"app.kubernetes.io/name": name}, "ports": ports},
    }


def deployment(name: str, container: dict, volumes: list[dict] | None = None) -> dict:
    container = {"securityContext": SECURE_CONTAINER, **container}
    return {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": name, "labels": labels(name)},
        "spec": {
            "replicas": 1,
            "selector": {"matchLabels": {"app.kubernetes.io/name": name}},
            "template": {
                "metadata": {"labels": labels(name)},
                "spec": {"securityContext": SECURE_POD, "containers": [container], "volumes": volumes or []},
            },
        },
    }


def ashgrove_service(name: str) -> list[dict]:
    probe = lambda path: {"httpGet": {"path": path, "port": "http"}, "periodSeconds": 10, "timeoutSeconds": 3}  # noqa: E731
    container = {
        "name": name,
        "image": IMAGE,
        "imagePullPolicy": "IfNotPresent",
        "args": [name, "--port", "8000"],
        "ports": [{"name": "http", "containerPort": 8000}],
        "envFrom": [{"configMapRef": {"name": "ashgrove-config"}}],
        "env": [{"name": "ASHGROVE_DATA_DIR", "value": "/data"}],
        "readinessProbe": probe("/readyz"),
        "livenessProbe": probe("/healthz"),
        "resources": {"requests": {"cpu": "50m", "memory": "96Mi"}, "limits": {"cpu": "500m", "memory": "256Mi"}},
        "volumeMounts": [{"name": "data", "mountPath": "/data"}],
    }
    dep = deployment(name, container, [{"name": "data", "emptyDir": {}}])
    dep["metadata"]["annotations"] = {
        "prometheus.io/scrape": "true",
        "prometheus.io/port": "8000",
        "prometheus.io/path": "/metrics",
    }
    return [dep, service(name, 8000)]


